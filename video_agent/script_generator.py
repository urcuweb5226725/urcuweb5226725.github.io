"""
视频脚本生成器
==============
这个脚本的作用：你输入一个主题，它帮你写出一段约100字的视频旁白文案。

比喻：就像一个"自动写作小助手"，你告诉它想聊什么话题，它帮你组织语言。
"""

import random  # 这是 Python 自带的"随机"工具，用来随机挑选句子

# ============================================
# 第一部分：准备好各种"句子模板"
# ============================================
# 就像填空题一样，{topic} 的位置会被替换成你输入的主题

# 开头句（吸引观众注意力）
OPENINGS = [
    "你知道吗？关于{topic}，有很多人其实都不太了解。",
    "今天我们来聊一个有趣的话题：{topic}。",
    "很多人问我关于{topic}的问题，今天就来解答一下。",
    "{topic}，这是一个值得深入了解的话题。",
    "说到{topic}，你第一时间会想到什么？",
]

# 中间内容（展开说明）
MIDDLES = [
    "其实，{topic}和我们的日常生活息息相关。",
    "从不同角度来看，{topic}有着独特的魅力。",
    "了解{topic}，可以让我们看到更广阔的世界。",
    "关于{topic}，最重要的一点是要保持好奇心。",
    "深入研究{topic}后，你会发现很多惊喜。",
]

# 结尾句（引导互动）
ENDINGS = [
    "如果你对{topic}也感兴趣，记得点赞关注哦！",
    "关于{topic}，你有什么看法呢？评论区见！",
    "这就是今天关于{topic}的分享，下期再见！",
    "希望这期关于{topic}的内容对你有帮助，我们下期见！",
    "{topic}的故事还有很多，想听的话就关注我吧！",
]


# ============================================
# 第二部分：生成脚本的函数
# ============================================
def generate_script(topic):
    """
    这个函数的作用：接收一个主题，返回一段完整的视频脚本

    参数：
        topic - 你想要的主题，比如"健康饮食"、"学习方法"等

    返回：
        一段约100字的视频脚本文字
    """

    # 第一步：从每个列表中随机挑选一句
    # random.choice() 就像"抽签"，随机抽一个
    opening = random.choice(OPENINGS)
    middle = random.choice(MIDDLES)
    ending = random.choice(ENDINGS)

    # 第二步：把 {topic} 替换成真正的主题
    # .format() 就像"填空"，把括号里的内容填进去
    opening = opening.format(topic=topic)
    middle = middle.format(topic=topic)
    ending = ending.format(topic=topic)

    # 第三步：把三部分拼接成完整脚本
    full_script = f"{opening}\n\n{middle}\n\n{ending}"

    return full_script


# ============================================
# 第三部分：主程序（程序从这里开始运行）
# ============================================
if __name__ == "__main__":
    # 这行的意思是：只有直接运行这个文件时，下面的代码才会执行

    print("=" * 50)
    print("    欢迎使用视频脚本生成器！")
    print("=" * 50)
    print()

    # 让用户输入主题
    topic = input("请输入视频主题（比如：健康饮食）：")

    # 检查用户是否输入了内容
    if topic.strip() == "":
        print("你没有输入主题哦，我用'生活小技巧'作为示例：")
        topic = "生活小技巧"

    print()
    print("-" * 50)
    print("生成的视频脚本如下：")
    print("-" * 50)
    print()

    # 调用函数生成脚本
    script = generate_script(topic)
    print(script)

    print()
    print("-" * 50)
    print(f"脚本长度：{len(script)} 个字符")
    print("-" * 50)
